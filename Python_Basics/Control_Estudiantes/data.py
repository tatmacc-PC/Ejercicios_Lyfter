import csv
from pathlib import Path

from actions import (
    SUBJECTS,
    confirm_action,
    is_valid_name,
    is_valid_section,
    student_exists,
)


# Save and read the CSV in the current working directory.
CSV_PATH = Path.cwd() / "students.csv"

# Define the CSV columns in a fixed order.
FIELDS = ["name", "section"] + list(SUBJECTS)


def export_students(students):
    if not students:
        print("No hay estudiantes para exportar.")
        return

    # Confirm before overwriting an existing file.
    if CSV_PATH.exists():
        if not confirm_action(
            "El archivo ya existe. ¿Desea sobrescribirlo?"
        ):
            print("Exportación cancelada.")
            return

    try:
        # Preserve accented characters and avoid extra blank lines.
        with CSV_PATH.open(
            "w",
            newline="",
            encoding="utf-8-sig",
        ) as file:
            writer = csv.DictWriter(file, fieldnames=FIELDS)

            writer.writeheader()
            writer.writerows(students)

        print(f"Se exportaron {len(students)} estudiantes.")
        print(f"Archivo: {CSV_PATH}")

    except (OSError, UnicodeError, csv.Error) as error:
        print(f"No se pudo exportar el archivo: {error}")


def validate_imported_student(row, row_number):
    # Reject rows with missing or extra columns.
    if None in row or any(value is None for value in row.values()):
        raise ValueError(
            f"Fila {row_number}: cantidad incorrecta de columnas."
        )

    name = row["name"].strip()
    section = row["section"].strip().upper()

    if not is_valid_name(name):
        raise ValueError(
            f"Fila {row_number}: nombre inválido."
        )

    if not is_valid_section(section):
        raise ValueError(
            f"Fila {row_number}: sección inválida."
        )

    student = {
        "name": " ".join(name.split()),
        "section": section,
    }

    # Convert CSV text values into numeric grades.
    for subject_key, subject_name in SUBJECTS.items():
        try:
            grade = float(row[subject_key])

        except ValueError:
            raise ValueError(
                f"Fila {row_number}: nota de {subject_name} inválida."
            ) from None

        # Reject out-of-range grades, NaN, and infinity.
        if not 0 <= grade <= 100:
            raise ValueError(
                f"Fila {row_number}: la nota de {subject_name} "
                "debe estar entre 0 y 100."
            )

        student[subject_key] = grade

    return student


def import_students(students):
    # Use a temporary list to preserve current data on failure.
    imported_students = []

    try:
        with CSV_PATH.open(
            "r",
            newline="",
            encoding="utf-8-sig",
        ) as file:
            reader = csv.DictReader(file, strict=True)

            # Require the headers generated by the export function.
            if reader.fieldnames != FIELDS:
                raise ValueError(
                    "El archivo no tiene las columnas esperadas."
                )

            for row_number, row in enumerate(reader, start=2):
                student = validate_imported_student(row, row_number)

                # Reject duplicate students in the imported file.
                if student_exists(
                    imported_students,
                    student["name"],
                    student["section"],
                ):
                    raise ValueError(
                        f"Fila {row_number}: estudiante duplicado."
                    )

                imported_students.append(student)

    except FileNotFoundError:
        print("No existe un archivo CSV previamente exportado")
        print("en la carpeta actual.")
        print(f"Archivo esperado: {CSV_PATH}")
        print("Primero utilice la opción 5.")
        return

    except (ValueError, UnicodeError, csv.Error) as error:
        print(f"No se pudo importar: {error}")
        print("Los datos actuales se conservaron.")
        return

    except OSError as error:
        print(f"No se pudo leer el archivo: {error}")
        return

    if not imported_students:
        print("El archivo no contiene estudiantes para importar.")
        return

    # Confirm before replacing current records.
    if students:
        if not confirm_action(
            "La importación reemplazará los estudiantes actuales. "
            "¿Desea continuar?"
        ):
            print("Importación cancelada.")
            return

    # Replace the contents while preserving the shared list.
    students[:] = imported_students

    print(f"Se importaron {len(students)} estudiantes correctamente.")